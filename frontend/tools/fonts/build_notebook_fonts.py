"""P5 public-range WOFF2 builder: no diary input, downloads, installs, or global font edits."""
import argparse
import hashlib
import json
import shutil
import tempfile
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

SOURCE_SHA256 = "39ad71264b588165b469e35e6afb162a378dacd1f95348160240ba9038ac3009"
SOURCE_COMMIT = "e8b5b48b79f19f29aa68b0a178eab3472ea9f7e8"
EXPECTED_TOOLS = {"fonttools": "4.51.0", "brotli": "1.0.9"}
PUBLIC_RANGES = [(0x20, 0x24F), (0x2000, 0x206F), (0x3000, 0x303F),
                 (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xFF00, 0xFFEF)]
FAMILY = "Quire Notebook WenKai"
ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "src/assets/fonts/notebook"
CSS = ROOT / "src/styles/notebook-fonts.css"
LICENSE = ROOT / "src/assets/fonts/LICENSES/LXGW-WenKai-OFL.txt"


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def public_codepoints():
    return {cp for first, last in PUBLIC_RANGES for cp in range(first, last + 1)}


def groups(codepoints):
    result = {}
    for cp in sorted(public_codepoints().intersection(codepoints)):
        result.setdefault(cp >> 8, []).append(cp)
    return result


def unicode_ranges(codepoints):
    points = sorted(set(codepoints))
    spans = []
    for cp in points:
        if spans and spans[-1][1] + 1 == cp:
            spans[-1][1] = cp
        else:
            spans.append([cp, cp])
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in spans)


def preflight(source):
    actual = {}
    for package in EXPECTED_TOOLS:
        try:
            actual[package] = version(package)
        except PackageNotFoundError:
            actual[package] = "missing"
    if actual != EXPECTED_TOOLS:
        raise RuntimeError(f"字体工具不匹配；未自动安装/升级：{actual}，预期{EXPECTED_TOOLS}")
    if not source.is_file():
        raise RuntimeError(f"缺少原始TTF：{source}；请提供既有官方缓存或--source，不会自动下载")
    if digest(source) != SOURCE_SHA256:
        raise RuntimeError("原始TTF SHA-256不匹配；未生成或覆盖任何文件")
    if not LICENSE.is_file() or "SIL OPEN FONT LICENSE" not in LICENSE.read_text().upper():
        raise RuntimeError("缺少既有OFL许可，请先核对来源；未生成字体")
    return actual


def rename(font, page):
    values = {1: FAMILY, 2: "Regular", 3: f"{FAMILY}-{page:04X}", 4: f"{FAMILY} Regular",
              6: f"QuireNotebookWenKai-{page:04X}", 16: FAMILY, 17: "Regular"}
    name = font["name"]
    for key, value in values.items():
        # Replace every legacy language/platform record; keep copyright/license untouched.
        records = [r for r in name.names if r.nameID == key]
        for record in records:
            name.setName(value, key, record.platformID, record.platEncID, record.langID)
        name.setName(value, key, 3, 1, 0x409)


def build(source, tools):
    from fontTools import subset
    from fontTools.ttLib import TTFont

    original = TTFont(source, recalcTimestamp=False)
    plan = groups(original.getBestCmap())
    original.close()
    if not plan:
        raise RuntimeError("原始字体与公开范围无交集")
    css = ["/* Generated by build_notebook_fonts.py; public ranges only. */"]
    manifest = {"family": FAMILY, "sourceCommit": SOURCE_COMMIT, "sourceSha256": SOURCE_SHA256,
                "tools": tools, "ranges": PUBLIC_RANGES, "shards": []}
    # Finish and verify all new assets in an isolated temporary directory first.
    with tempfile.TemporaryDirectory(prefix="quire-notebook-fonts-") as directory:
        stage = Path(directory)
        for page, points in sorted(plan.items()):
            font = TTFont(source, recalcTimestamp=False)
            options = subset.Options()
            options.layout_features = ["*"]
            sub = subset.Subsetter(options=options)
            sub.populate(unicodes=points)
            sub.subset(font)
            rename(font, page)
            font.flavor = "woff2"
            name = f"wenkai-{page:04x}.woff2"
            target = stage / name
            font.save(target)
            font.close()
            check = TTFont(target)
            cmap = sorted(check.getBestCmap())
            if cmap != points or check["name"].getDebugName(1) != FAMILY:
                raise RuntimeError(f"分包cmap/name校验失败：{name}")
            check.close()
            ranges = unicode_ranges(cmap)
            manifest["shards"].append({"file": name, "bytes": target.stat().st_size,
                                       "sha256": digest(target), "codepoints": cmap,
                                       "unicodeRange": ranges})
            css.append("@font-face {\n"
                       f'  font-family: "{FAMILY}";\n'
                       f'  src: url("../assets/fonts/notebook/{name}?no-inline") format("woff2");\n'
                       "  font-style: normal; font-weight: 400; font-display: swap;\n"
                       f"  unicode-range: {ranges};\n" + "}")
        css.append('.notebook-body { font-family: "Quire Notebook WenKai", "Kaiti SC", '
                   '"STKaiti", KaiTi, "Songti SC", "SimSun", serif; }\n')
        # Do not clobber unexpected/manual files or delete stale/untracked directories.
        for shard in manifest["shards"]:
            dest = ASSETS / shard["file"]
            if dest.exists() and digest(dest) != shard["sha256"]:
                raise RuntimeError(f"目标字体已有不同字节，停止而非覆盖：{dest}")
        if CSS.exists() and not CSS.read_text().startswith((
                "/* P5-1 source groundwork.", "/* Generated by build_notebook_fonts.py;")):
            raise RuntimeError("目标CSS非预期生成文件，停止而非覆盖")
        ASSETS.mkdir(parents=True, exist_ok=True)
        for shard in manifest["shards"]:
            shutil.copyfile(stage / shard["file"], ASSETS / shard["file"])
        (ASSETS / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
        shutil.copyfile(LICENSE, ASSETS / "OFL.txt")
        CSS.write_text("\n\n".join(css))
    sizes = [s["bytes"] for s in manifest["shards"]]
    print(json.dumps({"shards": len(sizes), "bytes": sum(sizes), "maxShardBytes": max(sizes),
                      "codepoints": sum(len(s["codepoints"]) for s in manifest["shards"]),
                      "tools": tools}, ensure_ascii=False))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(tempfile.gettempdir()) /
                        "quire-font-source-cache/LXGWWenKai-Regular.ttf")
    parser.add_argument("--check", action="store_true", help="只读预检，不下载、不写文件")
    parser.add_argument("--plan", action="store_true", help="只打印公开码点规则，不代表字体覆盖")
    args = parser.parse_args()
    if args.plan:
        print(json.dumps({"ranges": PUBLIC_RANGES, "bucket": 256,
                          "sourceSha256": SOURCE_SHA256}, ensure_ascii=False))
        return
    tools = preflight(args.source)
    if args.check:
        print("来源哈希/OFL/工具预检通过；未生成字体")
        return
    build(args.source, tools)


if __name__ == "__main__":
    main()
